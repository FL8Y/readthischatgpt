// Generates src/bank/packs.generated.ts: static imports of every bank pack file
// (Metro cannot glob). Skips gold.v2.json (imported by loader.ts), blueprint.json and review/.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const bankDir = join(root, 'data', 'bank');
const out = join(root, 'src', 'bank', 'packs.generated.ts');

function walk(dir) {
  const files = [];
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      if (name !== 'review') files.push(...walk(p));
    } else if (name.endsWith('.json') && name !== 'blueprint.json' && name !== 'gold.v2.json') {
      files.push(p);
    }
  }
  return files;
}

const files = walk(bankDir).map((f) => relative(bankDir, f).split('\\').join('/'));
let src = '// GENERATED by scripts/bank/genPacks.mjs (npm run bank:gen). Do not edit by hand.\n';
files.forEach((f, i) => { src += `import pack${i} from '../../data/bank/${f}';\n`; });
src += '\nexport interface BundledPack {\n  name: string;\n  items: unknown;\n}\n\n';
src += files.length === 0
  ? 'export const PACKS: BundledPack[] = [];\n'
  : `export const PACKS: BundledPack[] = [\n${files.map((f, i) => `  { name: '${f}', items: pack${i} },`).join('\n')}\n];\n`;
writeFileSync(out, src);
console.log(`wrote ${relative(root, out)} with ${files.length} pack file(s)`);
